#!/usr/bin/env python3
"""Render only original Colosseum hashchecked synthetic assets as C++ literals."""
from pathlib import Path
import argparse, base64, hashlib, json
p=argparse.ArgumentParser();p.add_argument("--output",type=Path);args=p.parse_args()
root=Path(__file__).parent
manifest=json.loads((root/'manifest.json').read_text())
out='// Original Colosseum synthetic black/silent profiling samples.\n// Generated by tools/server_lab/profiler_samples/generate.py; explicit M934 payload-byte deviation.\n// SPDX-License-Identifier: MIT; see tools/server_lab/profiler_samples/LICENSE.\n'
for row in manifest['samples']:
    data=(root/'assets'/row['file']).read_bytes()
    if len(data)!=row['bytes'] or hashlib.sha256(data).hexdigest()!=row['sha256']:
        raise ValueError('Generated sample integrity mismatch: '+row['file'])
    encoded=base64.b64encode(data).decode()
    out+='    {"'+row['file']+'",'+str(row['bytes'])+',"'+row['sha256']+'",\n'
    out+='\n'.join('     "'+encoded[i:i+100]+'"' for i in range(0,len(encoded),100))+'\n    },\n'
(args.output or root.parents[2]/'native/colosseum_server_v1/src/http/GeneratedSamples.inc').write_text(out)
