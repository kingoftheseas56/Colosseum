"""Build a versioned notes page from a tracked release document. No network."""
import hashlib
import html
import json
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def render(markdown, version="1.1.9"):
    # The release document uses headings, paragraphs, bullets and inline code.
    # Escape everything first; raw HTML, scripts and remote embeds never execute.
    def inline(text):
        return re.sub(r"`([^`]+)`", r"<code>\1</code>", html.escape(text))
    blocks = []
    for block in markdown.strip().split("\n\n"):
        text = " ".join(block.splitlines())
        if block.startswith("- "):
            items = []
            for line in block.splitlines():
                if line.startswith("- "): items.append(line[2:])
                elif items: items[-1] += " " + line.strip()
            blocks.append("<ul>" + "".join("<li>" + inline(item) + "</li>" for item in items) + "</ul>")
        elif block.startswith("## "):
            blocks.append("<h2>" + inline(text[3:]) + "</h2>")
        elif block.startswith("# "):
            blocks.append("<h1>" + inline(text[2:]) + "</h1>")
        else:
            blocks.append("<p>" + inline(text) + "</p>")
    return """<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Colosseum """ + html.escape(version) + """ — Release notes</title>
<style>body{margin:0;background:#101114;color:#e7e5de;font:18px/1.7 system-ui,sans-serif}main{max-width:780px;margin:auto;padding:48px 24px 96px}a{color:#f3ce4b}nav{font-size:15px;margin-bottom:48px}h1{font-size:clamp(32px,6vw,52px);line-height:1.15}h2{font-size:25px;margin-top:48px;color:#f3ce4b}li{padding:5px 0}code{overflow-wrap:anywhere;font-size:.9em}</style>
</head><body><main><nav><a href="/">Colosseum</a> / Release notes</nav><article>""" + "\n".join(blocks) + "</article></main></body></html>\n"


def build(source, version="1.1.9"):
    if not re.fullmatch(r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)", version):
        raise ValueError("version must be canonical X.Y.Z")
    page = render(source, version)
    return (f"// Generated by build_release_notes.py from docs/release-notes/v{version}.md.\n"
            + "export const notesSourceSha256 = " + json.dumps(hashlib.sha256(source.encode()).hexdigest()) + ";\n"
            + "export const notesETag = " + json.dumps('"' + hashlib.sha256(page.encode()).hexdigest() + '"') + ";\n"
            + "export const notesHtml = " + json.dumps(page, ensure_ascii=False) + ";\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", default="1.1.9")
    args = parser.parse_args()
    if not re.fullmatch(r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)", args.version):
        parser.error("version must be canonical X.Y.Z")
    source_path = ROOT / f"docs/release-notes/v{args.version}.md"
    source = source_path.read_text(encoding="utf-8")
    suffix = args.version.replace(".", "")
    destination = Path(__file__).parent / f"release_notes_{suffix}.mjs"
    destination.write_text(build(source, args.version), encoding="utf-8")


if __name__ == "__main__":
    main()
